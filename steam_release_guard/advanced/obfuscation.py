"""Explicit, version-gated Obfuz integration before Unity's IL2CPP step."""
from __future__ import annotations

import json
import re
import xml.etree.ElementTree as ET
from pathlib import Path

from .. import core as c, project_backup, transactions
from ..operations import GuardError, writer
from .common import ProtectionAdapter, changes, names, new_output, private_run, read_json, shape

PACKAGE = "com.code-philosophy.obfuz"
VERSION = "4.0.0"
SOURCE_COMMIT = "b83c53d4df525232a4d8e783d68995706b3a5d5d"
ROOT = "Assets/SteamReleaseGuard/AdvancedEditor"
CONFIG = "ProjectSettings/SteamReleaseGuardObfuscation.json"


def validate(project, value):
    shape(value, {"schema", "engine_version", "adapter", "tool_version", "assemblies", "reference_assemblies", "strings", "control_flow"})
    if project.engine != "unity" or value["schema"] != 1 or value["engine_version"] != project.version:
        raise GuardError("Unity project and exact config engine version must match.")
    c.require_supported(project)
    if value["adapter"] != "obfuz" or value["tool_version"] != VERSION:
        raise GuardError("Only the reviewed Obfuz 4.0.0 API is supported; other versions need review.")
    if type(value["strings"]) is not bool or type(value["control_flow"]) is not bool:
        raise GuardError("Protection switches must be booleans.")
    # These passes depend on a generated VM/runtime initialization. No unverified
    # initializer or secret material is generated by this adapter.
    if value["strings"] or value["control_flow"]:
        raise GuardError("This adapter enables symbol renaming only. String/control-flow passes require a separately validated runtime integration; NOT_VERIFIED.")
    assemblies = value["assemblies"]
    if not isinstance(assemblies, list) or not assemblies or len(assemblies) > 100:
        raise GuardError("Select explicit game assemblies and safe types; no default whole-project obfuscation.")
    for assembly in assemblies:
        shape(assembly, {"name", "include_types", "exclude_types", "rename_fields"})
        names([assembly["name"]])
        if "/" in assembly["name"] or assembly["name"].startswith(("Unity", "System", "Obfuz", "Microsoft")):
            raise GuardError("Select your own assembly, not an engine/framework/tool assembly.")
        names(assembly["include_types"])
        names(assembly["exclude_types"], patterns=True, empty=True)
        if type(assembly["rename_fields"]) is not bool:
            raise GuardError("rename_fields must be an explicit boolean (recommended false).")
    names([a["name"] for a in assemblies])
    names(value["reference_assemblies"], empty=True)
    for name in [*(a["name"] for a in assemblies), *value["reference_assemblies"]]:
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_.-]*", name) or name.endswith(".dll") or ".." in name:
            raise GuardError("Assembly names must be simple names without a path or .dll extension.")
    if set(value["reference_assemblies"]) & {a["name"] for a in assemblies}:
        raise GuardError("Obfuscated and referencing-only assemblies must be disjoint.")
    return value


def rules(config):
    root = ET.Element("obfuz")
    for item in config["assemblies"]:
        assembly = ET.SubElement(root, "assembly", name=item["name"])
        ET.SubElement(assembly, "type", name="*", obName="0", applyToMembers="*", applyToNestedTypes="1")
        for name in item["include_types"]:
            selected = ET.SubElement(assembly, "type", name=name, obName="1", applyToMembers="method", applyToNestedTypes="0")
            ET.SubElement(selected, "field", name="*", obName="1" if item["rename_fields"] else "0")
        # Obfuz's symbol policy applies matching rules in document order: last wins.
        for name in item["exclude_types"]:
            ET.SubElement(assembly, "type", name=name, obName="0", applyToMembers="*", applyToNestedTypes="1")
    ET.indent(root)
    return ET.tostring(root, encoding="utf-8", xml_declaration=True) + b"\n"


class ObfuzAdapter(ProtectionAdapter):
    def detect(self, project, tool_path=None):
        candidates = [Path(tool_path)] if tool_path else [project.root / "Packages" / PACKAGE]
        cache = project.root / "Library/PackageCache"
        if tool_path is None and cache.is_dir():
            candidates += sorted(cache.glob(PACKAGE + "@*"))
        found = []
        for path in candidates:
            if not (path / "package.json").is_file():
                continue
            data = read_json(path / "package.json")
            if data.get("name") == PACKAGE:
                found.append({"path": str(path), "version": data.get("version"),
                              "api_supported": data.get("version") == VERSION})
        return {"adapter": "obfuz", "installed_candidates": found,
                "status": "DETECTED" if found else "MISSING",
                "reason": "Version/path detection only; Unity must resolve this package at build time." if found else
                          "Obfuz package not found. Install a reviewed version yourself or provide --tool-path; nothing was downloaded.",
                "runtime": "NOT_VERIFIED", "reviewed_source": SOURCE_COMMIT}

    def plan(self, project, config):
        validate(project, config)
        # Install baseline Editor builder through the same single transaction.
        values = [(x.path, x.data, x.purpose) for x in c.plan(project)]
        source = Path(__file__).resolve().parents[2] / "adapters/unity-advanced"
        for name in ("SteamReleaseGuardObfuscation.cs", "SteamReleaseGuard.Obfuscation.Editor.asmdef"):
            values.append((ROOT + "/" + name, (source / name).read_bytes(), "Opt-in Obfuz build bridge (Editor only)"))
        values += [(CONFIG, (json.dumps(config, ensure_ascii=False, indent=2) + "\n").encode(), "Explicit obfuscation allowlist; no keys"),
                   (ROOT + "/rename.xml", rules(config), "Keep all names except reviewed selected types; exclusions win")]
        return changes(project, values)


def apply(project, config, **kwargs):
    if not any(x["api_supported"] for x in ObfuzAdapter().detect(project)["installed_candidates"]):
        raise GuardError("Reviewed Obfuz package missing; bridge was not installed.")
    return transactions.apply(project, planner=lambda: ObfuzAdapter().plan(project, config), **kwargs)


def build_preview(project, config, editor, output, evidence_dir):
    validate(project, config)
    if not project_backup.restored_roots(project.root):
        raise GuardError("Advanced engine execution requires a verified backup-restore project copy.")
    if ObfuzAdapter().plan(project, config):
        raise GuardError("Review and apply unity-plan first; bridge/config does not match.")
    editor = project_backup.safe_path(editor)
    if not editor.is_file() or editor.name.lower() != "unity.exe":
        raise GuardError("Choose the exact installed Unity Editor executable.")
    output = new_output(output, project.root)
    evidence = new_output(evidence_dir, project.root, output)
    return {"editor": str(editor), "output": str(output), "evidence": str(evidence),
            "engine_version": project.version, "runtime": "NOT_VERIFIED",
            "scope": "Run the local Editor on a restored copy; preserve original project and keys. Private logs/mapping stay outside depot."}


def build(project, config, editor, output, evidence_dir, *, operation=None, timeout=3600):
    with writer():
        preview = build_preview(project, config, editor, output, evidence_dir)
        evidence = new_output(evidence_dir, project.root, output, create=True)
        argv = [str(editor), "-batchmode", "-quit", "-projectPath", str(project.root), "-buildTarget", "Win64",
                "-executeMethod", "SteamReleaseGuard.Advanced.ObfuscatedBuild.BuildWindows", "-srgOutput", str(Path(output) / "Game.exe"),
                "-srgEvidence", str(evidence), "-logFile", "-"]
        record = {**preview, "status": "INCOMPLETE"}
        c.write_json(evidence / "execution.json", record)
        execution = private_run(argv, evidence, operation=operation, timeout=timeout)
        receipt_path = evidence / "obfuscation.json"
        receipt = read_json(receipt_path) if receipt_path.exists() else None
        if receipt is not None:
            shape(receipt, {"configuration", "artifact", "runtime", "engine_version", "tool_version", "executable_sha256", "assemblies"})
            if (receipt["configuration"] != "PASS" or receipt["artifact"] != "PASS" or receipt["runtime"] != "NOT_VERIFIED"
                    or receipt["engine_version"] != project.version or receipt["tool_version"] != VERSION
                    or not isinstance(receipt["assemblies"], list)):
                raise GuardError("Invalid/unsupported obfuscation evidence; no protection approved.")
            expected_names = {a["name"] for a in config["assemblies"]}
            actual_names = []
            for row in receipt["assemblies"]:
                shape(row, {"name", "before_sha256", "after_sha256", "renamed_selected_types"})
                if (row["name"] not in expected_names or type(row["renamed_selected_types"]) is not int or row["renamed_selected_types"] < 1
                        or any(not isinstance(row[k], str) or not re.fullmatch("[0-9a-f]{64}", row[k]) for k in ("before_sha256", "after_sha256"))
                        or row["before_sha256"] == row["after_sha256"]):
                    raise GuardError("Missing selected assembly rename evidence.")
                actual_names.append(row["name"])
            executable = Path(output) / "Game.exe"
            if set(actual_names) != expected_names or len(actual_names) != len(expected_names) or not executable.is_file() or c.file_digest(executable) != receipt["executable_sha256"]:
                raise GuardError("Obfuscation receipt is not bound to the generated game output.")
            if ObfuzAdapter().plan(project, config):
                raise GuardError("Adapter/config changed during build; review this incomplete evidence.")
        record.update(execution=execution, artifact=receipt, status="REVIEW" if execution["exit_code"] == 0 and receipt else "FAIL")
        c.write_json(evidence / "execution.json", record)
        return record
